	private static <T extends Item> DeferredItem<T> registerItem(String name, Tab tab, Supplier<T> item)
	{
		DeferredItem<T> holder = ITEMS.register(name, item);
		(switch (tab) { case GUNS -> GUNS_TAB_ITEMS; case CRAFTING -> CRAFTING_TAB_ITEMS; case ATTACHMENTS -> ATTACHMENTS_TAB_ITEMS; }).add(holder);
		return holder;
	}

	private static DeferredItem<GunItem> registerGun(String name, Supplier<GunItem> item)
	{
		DeferredItem<GunItem> holder = registerItem(name, Tab.GUNS, item);
		GUN_ITEMS.add(holder);
		return holder;
	}
